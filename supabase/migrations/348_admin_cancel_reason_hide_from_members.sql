-- ============================================================
-- 348_admin_cancel_reason_hide_from_members.sql
-- 「운영진 취소」를 회원의 취소 사유 목록에서 감춘다
-- ============================================================
--
-- ## 무엇을 고치나
--
-- cancel_reason 의 'admin_cancelled'(「운영진 취소」/「運営によるキャンセル」)는
-- **서버만 찍는 도장**이다 — 마이그레이션 288 의 cancel_event_ticket_admin()
-- 이 행사 예약을 관리자 대신 취소할 때 딸린 응모에 붙인다. 사람이 고르라고
-- 만든 항목이 아니다.
--
-- 그런데 288 이 이 행을 active=true 로 넣었고, 인플루언서의 「이 응모를
-- 취소」 사유 드롭다운(dev/js/mypage.js:749)은 받은 목록을 **그대로 전부**
-- 그린다. 그래서 본인이 취소하는 자리에 「運営によるキャンセル」이 선택지로
-- 떠 있었다.
--
-- 고르면 본인 취소가 「운영진 취소」로 기록된다:
--   · 사유별 집계에서 운영진이 취소한 건수가 부풀려진다
--   · 「운영진이 내 응모를 취소했다」는 문의가 와도 기록만으로는 반박 못 한다
--
-- ⚠️ cancel_application(원본 309)은 사유 코드를 **검증하지 않는다**(무엇이든
--    그대로 저장). 그래서 이 목록이 유일한 문이다 — 서버 쪽에 추가 가드가
--    있으리라 기대하지 말 것.
--
-- ## 운영 실측 (2026-08-19, 운영 데이터베이스)
--
--   cancel_reason_code  건수  처음         마지막
--   admin_cancelled      6    2026-08-06  2026-08-07   ← 전부 행사 캠페인(서버)
--   personal_reason      5    2026-05-19  2026-05-19
--   schedule_unavailable 3    2026-05-11  2026-08-07
--
-- 6건 전부 event_mode=true 인 검증용 행사 캠페인 = 서버가 넣은 것.
-- **회원이 고른 건 0건** — 문은 열려 있었지만 아직 아무도 들어가지 않았다.
-- 그래서 기존 데이터를 손볼 필요가 없다(이 파일은 UPDATE 1행뿐).
--
-- ## 왜 active=false 로 감추는 것이 안전한가 (핵심)
--
-- ① 서버는 active 를 안 본다 — cancel_event_ticket_admin() 은 이 코드를
--    문자열로 그대로 넣으므로 감춰도 **동작이 그대로**다.
-- ② 라벨 조회도 active 를 안 본다 — cancel_application(309)의 관리자 알림
--    라벨 조회에 active 조건이 없다. 마이그레이션 347 이 'withdrawal' 을
--    같은 이유로 active=false 로 넣은 것과 정확히 같은 판단이다.
-- ③ ★ 관리자 화면·엑셀은 **2026-08-19 이전이었다면 깨졌다.**
--    admin-influencers.js 의 ensureCancelReasonsCache() 가 활성 사유만
--    받아 와서, 감추는 순간 위 6건이 「운영진 취소」가 아니라 코드값
--    `admin_cancelled` 로 보였을 것이다. 같은 날 fetchCancelReasons() 에
--    { includeInactive: true } 를 붙여 **라벨 조회만** 비활성 포함으로
--    바꿨기 때문에 지금은 감춰도 계속 「운영진 취소」로 보인다.
--    ⚠️ 그 클라이언트 변경(커밋 32307785)이 배포된 뒤에 적용할 것.
--       순서가 뒤바뀌면 관리자 화면에 코드값이 그대로 뜬다.
-- ⑤ ★ 회원 화면도 같은 함정이 있었고, 이 파일과 **같은 커밋에서** 고쳤다.
--    dev/js/mypage.js 는 취소 사유 목록을 쓰는 자리가 둘인데(750행=고르는
--    드롭다운 / 908행=이미 취소된 응모의 지난 사유 표시) **저장해 둔 목록을
--    공유**해서, 감추는 순간 관리자가 취소한 예약을 가진 회원의 취소 상세가
--    사유 빈 칸(—)으로 보였다. 저장분을 목적별로 둘로 갈랐다
--    (_cancelReasonsCache=활성만 / _cancelReasonsAllCache=비활성 포함).
--    ⚠️ 이 둘을 다시 합치지 말 것 — 합치면 회원이 「운영진 취소」·「회원
--       탈퇴」를 자기 취소 사유로 고를 수 있게 된다(감추려던 것이 되살아난다).
--    ⚠️ 이 결함은 348 이 만든 것이 아니다 — 마이그레이션 347 의 'withdrawal'
--       이 이미 같은 처지였다. 348 은 대상을 하나 더 늘릴 뿐이다.
--    회원 화면에서 취소 사유 라벨을 그리는 자리는 전수 검색 결과 이 한 곳뿐
--    (grep 'cancel_reason_code' dev/js dev/lib — 관리자 파일 제외 시 1건).
--    관리자 취소 알림 문구는 cancel_event_ticket_admin() 이 고정 일본어를
--    직접 넣으므로 이 목록과 무관하다.
--
-- ⑥ 관리자 「기준 데이터」 화면에는 애초에 안 뜬다 — 그 화면은 정해진 7종
--    (채널·카테고리·콘텐츠 종류·NG·참여방법·반려사유·주의사항)만 편집하고
--    cancel_reason 은 그 목록에 없다. 즉 이 값을 화면에서 되돌릴 길이 없고,
--    되돌리려면 아래 「되돌리는 방법」의 조회를 직접 돌려야 한다.
--
-- ## 적용 순서 (★ 지키지 않으면 화면이 깨진다)
--   개발 → 확인 → 운영. (양쪽 모두 288 이 적용돼 있어 대상 행이 존재한다)
--
--   ⚠️ **데이터베이스보다 코드가 먼저** 나가야 한다. 이 파일이 감추는 근거는
--      ③④⑤ 의 클라이언트 수정 세 가지이고, 그것들이 없는 서버에 이 UPDATE 만
--      먼저 적용하면:
--        · 관리자 화면·엑셀에 「운영진 취소」 대신 코드값이 그대로 뜨고
--        · 회원의 취소 상세에 사유가 빈 칸으로 뜬다
--      개발서버는 이미 배포됨(커밋 32307785 + 회원 화면 수정). 운영은 아직이므로
--      **운영 데이터베이스 적용은 dev → main 배포 이후**.
--
-- ============================================================

BEGIN;

UPDATE public.lookup_values
   SET active = false
 WHERE kind = 'cancel_reason'
   AND code = 'admin_cancelled'
   AND active IS DISTINCT FROM false;

-- 위 UPDATE 가 0행이어도 정상이다(이미 감춰져 있는 경우 — 재적용 안전).

COMMIT;

