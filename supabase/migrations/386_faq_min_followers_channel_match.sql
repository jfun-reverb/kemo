-- 386_faq_min_followers_channel_match.sql
-- 자주 묻는 질문 자동응답 「팔로워 수 부족」 안내를 채널 조건 3갈래에 맞춘다.
--
-- 왜 고치나
--   그 답변은 「・필요 팔로워: {required}명 이상」 / 「・현재 팔로워: {current}명」 두 줄인데,
--   화면(dev/js/messaging.js `_buildFaqCtx`)이 `campaigns.min_followers` 숫자 하나와
--   **본인 대표 SNS** 만 보고 값을 채웠다. 채널 조건이 늘어난 뒤 두 곳이 틀렸다 —
--     ① 「그리고(&)」 캠페인은 `min_followers` 가 0 이라 값이 안 만들어져
--        **「필요 팔로워」 줄이 통째로 사라졌다**(조건이 없는 것처럼 보인다).
--     ② 「또는(or)」 캠페인에서 대표 SNS 가 그 캠페인에 없는 채널이면
--        **캠페인과 무관한 숫자**를 「현재 팔로워」로 보여줬다.
--
-- 무엇을 바꾸나 (본문 텍스트만 — 노드·구조·활성 상태는 그대로)
--   ① 두 값 자리에서 「명 이상」·「명」 접미사를 뺀다.
--      이제 화면이 채널 이름까지 붙인 완성 문구를 넣는다
--      (예: 「Instagram 1,000명 이상 / TikTok 5,000명 이상」).
--      ⚠️ 접미사를 문장에 남겨 두면 「… 1,000명 이상명 이상」이 된다.
--   ② 마지막 문장의 「이 캠페인이 기준으로 정한 SNS」 → 「이 캠페인이 정한 SNS」.
--      기준 채널이 하나라는 전제가 「또는」·「그리고」에서 더는 성립하지 않는다.
--   ③ 첫 줄 「이 캠페인은 최소 팔로워 수 조건이 있습니다.」 → 자리표시 {intro}.
--      그 문장이 본문에 박혀 있어 **조건이 없는 캠페인(리뷰어형·행사)에도 그대로 떴다** —
--      바로 아래 두 줄은 값이 없어 빠지므로, 조건이 있다고 해 놓고 아무것도 안 보여 주는
--      답변이 됐다. 이제 화면이 조건 유무를 보고 두 문장 중 하나를 넣는다.
--      ⚠️ 이 한 줄의 문구만 본문이 아니라 번역 파일(dev/lib/i18n/{ko,ja}.js 의
--         `messaging.faqFollowerIntroHas` / `…None`)에 있다. 관리자 화면에서 못 고친다.
--         {intro} 를 지우면 첫 줄이 없어질 뿐 나머지는 그대로 동작한다.
--
-- 🔴 적용 순서 — **이 마이그레이션을 먼저, 앱 배포를 나중에.**
--   앱이 먼저 나가면 옛 본문의 「명 이상」이 그대로 남아 접미사가 두 번 붙는다.
--   이 순서로 하면 배포 전까지 「・필요 팔로워: 1000」(접미사 없음)으로 잠깐 밋밋할 뿐
--   틀린 정보는 안 나간다.
--
-- ⚠️ 이 노드의 옛 정의는 146(최초 시드)·155(문구 정정)에 있다.
--   나중에 그 파일을 다시 돌리면 **이 정정이 되돌아가** 접미사가 두 번 붙는다.
--   본문을 다시 손댈 때는 번호가 가장 큰 정의(이 파일)를 기준으로 삼을 것.
--
-- 대상 노드: Q1-1-c 팔로워 수 부족 (00000002-0000-0000-0001-000000000013)
-- 데이터 변경 범위: faq_nodes 1행의 body_ko·body_ja

UPDATE public.faq_nodes
SET
  body_ko = '{intro}
・필요 팔로워: {required}
・현재 팔로워: {current}
1. 아래 버튼으로 마이페이지 SNS 계정을 엽니다.
2. 팔로워 수를 지금 최신 인원으로 고칩니다.
3. 고친 뒤 다시 응모해 보세요.
팔로워 조건은 이 캠페인이 정한 SNS의 팔로워 수로 확인합니다. 리뷰어형(구매형) 캠페인은 팔로워 조건이 없습니다.',
  body_ja = '{intro}
・必要なフォロワー数：{required}
・あなたの現在のフォロワー数：{current}
1. 下のボタンからマイページのSNSアカウントを開きます。
2. フォロワー数を、いまの最新の人数に直します。
3. 直したあと、もう一度ご応募をお試しください。
フォロワーの条件は、このキャンペーンが指定したSNSのフォロワー数で確認します。なお、レシート提出型（購入型）のキャンペーンには、フォロワー数の条件はありません。'
WHERE id = '00000002-0000-0000-0001-000000000013'::uuid;

