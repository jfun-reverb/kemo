-- 무엇을 하나 — 행 추가만. 기존 행은 단 한 줄도 UPDATE 하지 않는다.
--   [A] tier_min_slots        1행 — 최소 모집 인원(count). 시드 1(=아무도 안 막는다)
--   [B] reviewer_recruit_fee_krw_tmin   1행 — 리뷰어 「소량」 구간 모집비. 8,500
--   [C] seeding_fee_krw_{채널}_tmin     5행 — 시딩 「소량」 구간 진행비. 🔴 가짜 값(99021~99025) —
--       기존 20행과 같은 규칙(442 머리말) — 0 으로 넣으면 "무료"라는 정상 값과 구분이 안 된다.
--   → 적용 뒤 quote_settings 는 33 + 7 = 40행.
--
-- ------------------------------------------------------------
-- 🔴 이 파일에는 절대 안 넣는 것 — 값 변경·라벨 뜻 뒤집기·함수 재정의
-- ------------------------------------------------------------
--   tier_slots_t100 을 100→150 으로 바꾸는 것, 기존 tier_slots_* 4행·이 파일이 만드는 tmin 7행의
--   "설명형" 라벨(최소 인원과의 관계 등), quote_settings.unit 컬럼 COMENT, 판정식 재정의는
--   전부 다음 파일(459)에 있다 — 사양서 §3-8 이 "①이 값 변경까지 하면 옛 판정식이 새 값을
--   읽어 조용히 금액이 바뀐다"고 명시한 것과 같은 이유로, 이번 라벨 변경도 ①에 안 둔다
--   (①과 ②를 동시에 적용하지 않는 배포가 있을 수 있고, ①만 적용된 상태에서 라벨이 먼저
--   바뀌면 아직 안 쓰이는 값을 "이미 이렇게 동작한다"고 읽게 된다 — 코디네이터 지시, 2026-09-21).
--   여기 넣는 라벨은 전부 **당장 뜻이 바뀌지 않는 플레이스홀더**뿐이다(아래 참고).
--
-- ------------------------------------------------------------
-- 🔴 이 파일에서 쓰는 라벨은 "당장은" 맞는 말이다 — 나중에 뒤집히는 것은 tier_slots_* 뿐이다
-- ------------------------------------------------------------
--   tier_min_slots 는 **브랜드 새 행**이라 "뒤집힐 예전 뜻"이 없다 — 처음부터 "최소 모집 인원"
--   이라는 뜻 하나뿐이라 최종 라벨을 바로 써도 안전하다.
--   reviewer_recruit_fee_krw_tmin·seeding_fee_krw_*_tmin(소량 구간 단가) 도 이 파일 시점에는
--   "최소 인원과 같아지면 안 쓰인다"는 관계가 아직 없다(tier_min_slots 시드값이 1 이라 §3-3 표대로
--   1명부터 받으므로 tmin 구간은 항상 쓰인다) — 그래서 여기서는 **짧은 이름만**("소량") 쓰고,
--   "최소 인원과 같아지면 안 쓰일 수 있다"는 관계 설명은 459 가 붙인다(코디네이터 지시 ③).
--
-- ------------------------------------------------------------
-- sort_order — 🔴 **각 묶음의 「그 채널 블록 바로 앞」**에 넣는다. 기존 행은 한 줄도 안 건드린다.
--   기존 배치가 채널마다 10 단위 블록이라(피드 40~43 · 릴스 50~53 · X 60~63 · 틱톡 70~73 ·
--   유튜브 80~83) **앞자리가 비어 있다** — 39·49·59·69·79.
--   🔴 **리뷰어만 예외로 묶음 끝(27)** 이다 — 20~26 이 이미 차 있고(20 은 송금 수수료),
--   19·20 어느 쪽에 넣어도 **송금 수수료가 모집비 사이에 낀다.** 붙일 자리가 없어 끝에 둔다.
--   ⚠️ 리뷰어는 7행뿐이라 찾기 어렵지 않다 — 채널마다 블록이 있는 시딩(25행)과 사정이 다르다.
--   ⚠️ `sort_order` 에 유일 제약이 없어 **겹쳐도 오류가 안 난다** — 겹치면 `key` 알파벳순으로
--   조용히 자리가 바뀐다(2026-09-21 검토에서 20 이 겹치는 것을 잡았다).
--   ⚠️ 그냥 표 끝에 몰면 「소량」 5행이 채널과 떨어져, **운영 배포 전에 시딩 25행을 손으로
--   채울 때** 어느 채널 것인지 찾기 어렵다(지금 시딩 단가는 전부 가짜 값이라 반드시 채워야 한다).
--   ⚠️ 구간 순서상 「소량」이 가장 앞이라 블록 **앞**이 맞다 — 뒤에 두면 표가 라이트→…→500건→소량 이 된다.
-- (옛 설명) 기존 행을 한 줄도 안 건드리려고 전부 "그 그룹의 끝"에 이어 붙인다
-- ------------------------------------------------------------
--   구간(12~15) 다음 16 · 리뷰어(20~26) 다음 27 · 시딩 각 채널 블록(40~83) 대신 채널별로
--   묶지 않고 시딩 tmin 5행을 90~94 로 몰아 시딩 표 맨 끝에 둔다. 기존 24행의 sort_order를
--   전혀 바꾸지 않기 위한 선택이다(채널마다 끼워 넣으려면 그 채널의 t50 이후 3행을 전부
--   +1 해야 해서 "행 추가만"이 깨진다). 화면 정렬만 살짝 부자연스럽고 데이터 정확성과는 무관.
--
-- 롤백: 이 파일이 만든 7행만 DELETE(맨 아래 「되돌리기」).
