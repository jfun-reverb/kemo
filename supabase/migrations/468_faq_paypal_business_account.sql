   is_human_handoff, relevant_stages, sort_order, active)
VALUES
  ('00000002-0000-0000-0005-000000000004'::uuid,
   '00000001-0000-0000-0000-000000000005'::uuid,
   'item',
   '「PayPal 비즈니스 계정」이 왜 필요한가요?',
   '「PayPalビジネスアカウント」は、なぜ必要ですか？',
   '캠페인 보수는 상품·서비스에 대한 대가에 해당합니다. PayPal에서는 이런 대금을 개인 계정으로 받을 수 없다고 정해 두었습니다.
그래서 보수를 받으실 때는 비즈니스 계정을 부탁드리고 있습니다.
1. 지금 개인 계정을 쓰고 계셔도 새로 만들 필요는 없습니다. PayPal의 「설정」에서 바꾸실 수 있습니다.
2. 바꾸실 때 하시는 일의 내용 등을 입력하는 화면이 나올 수 있습니다. 모르는 항목이 있으면 아래 「직접 문의」로 상담해 주세요.
3. 바꾸신 뒤 본인확인을 마쳐 주세요. 이것이 끝나지 않으면 돈을 받거나 인출하실 수 없습니다.
등록하신 이메일 주소가 바뀐 경우에는 마이페이지에서 새 주소로 고쳐 주세요.',
   'キャンペーンの報酬は、商品やサービスに対するお支払いにあたります。PayPalでは、こうしたお支払いを個人アカウントで受け取ることができないと決められています。
そのため、報酬のお受け取りにはビジネスアカウントをお願いしています。
1. いま個人アカウントをお使いの方も、新しく作り直す必要はありません。PayPalの「設定」から切り替えられます。
2. 切り替えのときに、お仕事の内容などを入力する画面が出ることがあります。分からない項目があれば、下の「直接お問い合わせ」からご相談ください。
3. 切り替えたあと、本人確認（ほんにんかくにん）をすませてください。これが終わっていないと、お金を受け取ったり引き出したりできません。
ご登録のメールアドレスが変わった場合は、マイページで新しいアドレスに直してください。',
   'navigate', '#mypage-paypal', 'PayPal 설정 보기', 'PayPalを確認する',
   false, ARRAY['done'], 40, true)
