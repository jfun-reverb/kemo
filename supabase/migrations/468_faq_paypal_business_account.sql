-- ── 왜 필요한가 ──
--   캠페인 참여방법이 「PayPal 비즈니스 계정으로 송금 가능한 분만」이라 적는데,
--   인플루언서가 그 이유와 방법을 모른다. PayPal 일본 규약은 개인 계정의 상용 목적
--   사용을 금지한다(사양서 §2 ①). 같은 배포에서 마이페이지 PayPal 화면의
--   「계정이 없어도 된다」 문구도 비즈니스 계정 안내로 바꾼다(사양서 §3-3 가).
--
-- ── 어디에 붙는가 ──
--   카테고리 5 「보수·정산」(00000001-0000-0000-0000-000000000005) 아래.
--   운영 실측(2026-09-28): 항목 3개(10 수령 방법 / 20 PayPal 변경 / 30 최대 금액)
--   → sort_order = 40. id …0005-000000000004 는 비어 있음.
--
-- ── 문안에서 일부러 뺀 것 (사양서 §3-2) ──
--   「簡単」「無料」, 「凍結/거절된다」(확인 안 된 예측), 屋号 칸에 무엇을 적으라는 안내,
--   「설정」 아래 메뉴 이름(PayPal 화면 이름은 바뀐다), 「이메일은 그대로」 단정.
--   ⚠️ 3번(본인확인)은 빼면 안 된다 — 안 하면 바꿔도 돈을 받거나 인출할 수 없다.
--
-- ── relevant_stages ──
--   추천 순서만 정한다(걸러 내지 않는다 — dev/js/messaging.js 단계 일치 우선 정렬).
--   같은 주제인 Q5-1(보수 수령 방법)과 같게 ['done'].
--
-- ── 되돌리기 ──
--   DELETE FROM public.faq_nodes WHERE id = '00000002-0000-0000-0005-000000000004';
--   (faq_interactions 는 node_id 참조가 CASCADE 라 함께 정리된다)
