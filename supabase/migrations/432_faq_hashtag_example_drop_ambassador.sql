UPDATE public.faq_nodes
SET
  body_ko = replace(body_ko, ' · #アンバサダー 중 지정된 것', ' 중 지정된 것'),
  body_ja = replace(body_ja, '・#アンバサダー のうち指定されたもの', ' のうち指定されたもの'),
  updated_at = now()
WHERE id = '00000002-0000-0000-0003-000000000003'::uuid
  AND (body_ko LIKE '%#アンバサダー%' OR body_ja LIKE '%#アンバサダー%');

COMMIT;
