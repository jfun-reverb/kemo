-- ============================================================
-- ① ★ 359 의 관례를 그대로 베끼면 차단이 통째로 무효가 된다
-- ============================================================
--   359 의 차단 장치 셋은 전부 이렇게 시작한다:
--       IF auth.uid() IS NULL THEN RETURN NEW; END IF;   -- 예약 실행·서비스 키는 통과
--
--   🔴 **브라우저 회원가입도 로그인 정보가 없다.** 이 줄을 복사하면 **모든 가입이
--     통과해 차단이 통째로 무효**가 되고, **아무 오류도 안 난다** — 그냥 아무도 안
--     막힌다. 마이그레이션 312 사고와 같은 유형(막는 변경의 실패는 조용하다).
--
--   → **이 트리거만 관례가 반대다: 기본은 막고, 예외만 통과.**
--
--   | 통과시키는 것 | 왜 |
--   |---|---|
--   | `public.is_admin()` 이 참 | 관리자 초대(245)가 `auth.users` 에 직접 넣는다. 막히면 6개월 안에 그 사람을 관리자로 못 부른다 |
--
--   ⚠️ 시드·시험 계정을 서비스 키로 직접 넣는 경우는 통과 조항이 없어 막힌다 — 그건
--     **눈에 보이는 실패**라 괜찮다(차단 행을 지우고 다시 넣으면 된다). 반대로
--     통과시켜 놓으면 **안 보이는 무효**가 된다.
--
-- ============================================================
-- ② 회원에게는 이 메시지가 그대로 보이지 않는다
-- ============================================================
--   회원가입 인증 서비스가 우리 메시지를 지우고 일반 오류로 덮는다. 그래서
--   **화면이 가입 전에 먼저 대조**해 안내 문구를 보여준다(같은 묶음의 화면 몫).
--   이 트리거는 **화면을 안 거치는 경로의 최종 방어선**이다.
--
--   ⚠️ 그 결과 여기서 막히면 관리자 오류 로그에 「미해결」로 쌓인다. 그런데
--     **그 오류를 「정상 거부」 목록에 넣을 수 없다** — 인증 서비스가 우리 코드를
--     지워 버려, 넣으려면 일반 데이터베이스 오류 문구를 통째로 넣어야 하고 그러면
--     **진짜 장애까지 함께 침묵한다.**
--   → 화면이 먼저 걸러 주므로 정상 회원에게는 이 오류가 한 번도 안 난다.
--     여기 쌓이는 것은 **개발자 도구로 우회를 시도한 흔적**이라, 오히려 유용하다.
--
-- ============================================================
-- ③ 시행일 잠금을 여기 걸지 않는 이유
-- ============================================================
--   담는 쪽(361)에만 걸었다. 담긴 해시가 없으면 이 트리거는 **아무것도 안 막는다** —
--   조건을 두 곳에 두면 어긋날 자리만 는다.
--
-- ============================================================
-- ④ 되돌리기
-- ============================================================
--   DROP TRIGGER IF EXISTS trg_withdrawal_signup_block ON auth.users;
--   DROP FUNCTION IF EXISTS public.check_withdrawal_signup_block();
--   기존 함수·트리거를 하나도 재정의하지 않는다(014 의 `on_auth_user_created` 는
--   삽입 **후** 트리거라 이것과 별개로 그대로 돈다).
--
-- ⚠️ **적용 순서: 361 → 362.** 반대면 없는 함수를 불러 **모든 가입이 실패한다.**
-- ============================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.check_withdrawal_signup_block()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
BEGIN
  -- 통과 ① 관리자 — 관리자 초대(245)가 auth.users 에 직접 넣는 경로.
  --   ⚠️ 여기 `auth.uid() IS NULL THEN RETURN NEW` 를 **절대 추가하지 말 것**.
  --      회원가입이 바로 그 상태로 들어온다(위 헤더 ①).
  IF public.is_admin() THEN
    RETURN NEW;
  END IF;

  IF NEW.email IS NOT NULL
     AND public.is_email_withdrawal_blocked(NEW.email) THEN
    RAISE EXCEPTION 'email_withdrawal_blocked: 탈퇴 후 재가입 제한 기간입니다'
      USING ERRCODE = 'P0001';
  END IF;

  RETURN NEW;
END;
$fn$;

COMMENT ON FUNCTION public.check_withdrawal_signup_block() IS
  '[362] 탈퇴 확정 후 6개월 안에 같은 이메일로 다시 가입하는 것을 막는다. '
  '🔴 **관례가 359 와 반대다** — 359 의 차단 장치들은 「로그인 정보가 없으면 통과」로 '
  '시작하지만, 회원가입이 바로 그 상태라 그 줄을 넣으면 **모든 가입이 통과해 차단이 '
  '조용히 무효**가 된다. 여기서는 기본이 거부이고 관리자만 통과한다. '
  '⚠️ 회원에게는 이 메시지가 안 보인다(인증 서비스가 일반 오류로 덮는다) — 화면이 '
  '가입 전에 먼저 대조해 안내하고, 이 트리거는 화면을 안 거치는 경로의 최종 방어선이다.';

DROP TRIGGER IF EXISTS trg_withdrawal_signup_block ON auth.users;
CREATE TRIGGER trg_withdrawal_signup_block
  BEFORE INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.check_withdrawal_signup_block();

COMMIT;

