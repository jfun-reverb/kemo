-- ── [1] 적용 전 확인 (BEGIN 밖에서 먼저 돌린다) ───────────────────
--   🔴 고정된 기대값과 비교하지 않는다.
--      「대상이 N명인지 확인하고 다르면 멈춘다」로 두면, 조사일과 적용일 사이에
--      가입자가 늘었을 때 **정상인데 멈춘다.** 그런 확인은 한 번 헛발동하면
--      다음부터 아무도 안 본다. 그래서 **변하지 않는 수 하나만** 고정으로 본다.
--
-- SELECT
--   count(*)                                                        AS 전체_회원,
--   count(*) FILTER (WHERE created_at <  '2026-04-13T16:35:00+09:00')               AS 기준일_이전,
