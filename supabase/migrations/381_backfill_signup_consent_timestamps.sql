--   🔴 「기준일_이전 = 2」 가 아니면 **멈춘다.** 과거 데이터라 변할 수 없는 수이고,
--      다르다면 기준일 판단이나 조회 대상이 틀렸다는 뜻이다.
--   ⚠️ 나머지 넷은 그날 값을 그대로 적어 두고, [2] 실행 뒤 [4]와 대조한다.

