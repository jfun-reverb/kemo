-- ── [2] 소급 ─────────────────────────────────────────────────────
--   ⚠️ WHERE 의 세 조건은 각각 위 「안 손대는 것」 ①③에 대응한다. 하나라도 빼면
--      기준일 이전 행이나 이미 값이 있는 행을 건드리게 된다.
--   ⚠️ 두 칸을 **따로** 판정하지 않고 「둘 다 빈 행」만 고른다 — 한쪽만 채워진
--      행이 생긴 적은 없지만, 생겼다면 그건 이 소급이 아니라 사람이 봐야 할 상태다.
UPDATE public.influencers
   SET terms_agreed_at   = created_at,
       privacy_agreed_at = created_at
 WHERE created_at        >= '2026-04-13T16:35:00+09:00'
   AND terms_agreed_at   IS NULL
   AND privacy_agreed_at IS NULL;

COMMIT;

