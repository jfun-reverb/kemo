-- ── 왜 채우는가 ────────────────────────────────────────────────
--   🔴 기준 시각 = 2026-04-13T16:35:00+09:00 (일본·한국 시각)
--      근거 — 커밋 aee049c2 「가입 폼에 약관·개인정보 동의 체크박스 추가」가
--      작성 16:32:48 · main 병합 16:32:50 (`git log --date=iso-local` 로 직접 확인).
--      배포 소요를 감안해 몇 분 여유를 둔 값이다.
--      ⚠️ **날짜만 쓰면 안 된다.** '2026-04-13' 은 시간대가 없어 UTC 자정,
--      곧 일본 시각 **09:00** 으로 해석된다. 실제 배포는 16:32 이므로 그 사이
--      약 7시간 30분에 가입한 사람이 **체크박스가 없던 때 가입했는데 동의한 것으로**
--      기록된다 — 이 파일이 아래에서 금지한 바로 그 일이다.
--      (이 저장소 규칙 `.claude/rules/release-timing.md` 「타임존 명시 의무」)
--
--   가입 폼은 그 시각(커밋 aee049c2 「가입 폼에 약관·개인정보 동의 체크박스
--   추가」)부터 **동의를 필수로 받아 왔다.** 체크하지 않으면 가입 자체가 안 된다.
--   그런데 그 값을 회원 행에 저장하는 코드가 없어, **동의는 실제로 받았는데
--   받은 시각만 비어 있는** 상태가 이어졌다.
--   → 그래서 이 소급은 「안 받은 동의를 받은 것처럼 꾸미는 것」이 아니라,
--      **이미 일어난 사실의 시각을 채우는 것**이다. 그 시각으로 가입일
--      (created_at)을 쓰는 이유는, 동의가 가입과 같은 순간에 일어났기 때문이다.
--
-- ── 손대는 것 / 안 손대는 것 ──────────────────────────────────
--   손대는 것 : terms_agreed_at, privacy_agreed_at  ← created_at 으로 채움
--   🔴 안 손대는 것 셋
--     ① 기준 시각 이전에 가입한 행 — 그때는 동의 체크박스가
--        **없었다.** 받지 않은 동의를 채우면 그건 사실이 아닌 기록이 된다.
--        (현재 2명. 이 수는 과거라 변하지 않는다 — 아래 [1]의 유일한 고정값)
--     ② marketing_agreed_at — 마케팅 동의는 **선택**이라 가입과 함께 일어났다고
--        볼 수 없다. 별도 항목이고 이 소급의 대상이 아니다.
--     ③ 이미 값이 있는 행 — 덮어쓰면 **진짜 기록이 소급값으로 바뀐다.**
--        (사양서 기준 운영 1명 — 감사용 계정. ⚠️ 이 수는 **서버마다 다르다** —
--        개발서버 실측은 4건이었다(아래 [3] 참조). WHERE 절은 개수와 무관하게
--        「값이 있으면 무조건 제외」하므로 이 차이가 소급 안전성에는 영향이 없다)
--
-- ── 🔴 적용 순서 ──────────────────────────────────────────────
--   이 파일(설계 3)을 **설계 1(가입 폼 값이 저장되게 하는 것)보다 먼저** 적용한다.
--   순서가 뒤집히면 그 뒤 가입자의 **진짜 기록**과 이 소급값이 같은 모양이 되어
--   **영영 구분할 수 없다.** 되돌리기(아래 [3])도 그때는 쓸 수 없다.
--
-- ⚠️ 소급했다는 표시를 따로 남기지 않는다(사용자 결정).
